/**
 * 토큰 빌드 — tokens.json (소스) → src/styles/globals.css 의 :root / .dark (생성물).
 *
 * 사용: pnpm tokens
 *
 * - 입력: templates/assets/tokens/tokens.json (color.{light,dark} + radius)
 * - 출력: globals.css 의 `/* tokens:start *​/ ~ /* tokens:end *​/` 마커 사이
 * - 마커 밖(@theme inline, @custom-variant 등)은 보존
 * - 무의존 (Node 내장만) — preset 경량 유지
 *
 * 디자이너는 tokens.json 값만 바꾸고 `pnpm tokens` 실행 → React 코드 변경 0 으로
 * 모든 bg-primary / text-foreground 등이 새 토큰 값으로 전환된다.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const presetRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokensPath = join(presetRoot, "templates/assets/tokens/tokens.json");
const cssPath = join(presetRoot, "src/styles/globals.css");

const tokens = JSON.parse(readFileSync(tokensPath, "utf-8"));

const colorVars = (mode) =>
  Object.entries(tokens.color)
    .map(([name, t]) => `  --${name}: ${t.$value[mode]};`)
    .join("\n");

const radiusVar = tokens.radius?.base ? `\n\n  --radius: ${tokens.radius.base.$value};` : "";

const block =
  `/* tokens:start — auto-generated by 'pnpm tokens' from tokens.json. DO NOT EDIT. */\n` +
  `:root {\n${colorVars("light")}${radiusVar}\n}\n\n` +
  `.dark {\n${colorVars("dark")}\n}\n` +
  `/* tokens:end */`;

const css = readFileSync(cssPath, "utf-8");
const markerRe = /\/\* tokens:start[\s\S]*?\/\* tokens:end \*\//;

if (!markerRe.test(css)) {
  console.error("✗ globals.css 에 /* tokens:start */ ~ /* tokens:end */ 마커가 없습니다.");
  process.exit(1);
}

writeFileSync(cssPath, css.replace(markerRe, block), "utf-8");
console.log(`✓ globals.css tokens regenerated (${Object.keys(tokens.color).length} colors, light+dark)`);
